const router = require('express').Router();
const c = require('./workflow.controller');
const { authenticate } = require('../../middleware/auth.middleware');
const { requireRole } = require('../../middleware/rbac.middleware');
const { clinicalAccess, visitAccess, orgContext, assignedStaff, notificationTarget } = require('../../middleware/clinical-access.middleware');
const { auditLog } = require('../../middleware/audit.middleware');
router.use(authenticate);
const clinical = (resource = 'visit', access = 'read', roles, id = req => req.params.id || req.body.visitId) => clinicalAccess({ resource, access, roles, id });
const administration = (resource = 'visit', id = req => req.params.id || req.body.visitId) => visitAccess({ resource, id, administrative: true, roles: ['hospital_admin', 'doctor', 'receptionist'] });
router.post('/tokens/generate', requireRole(['patient']), c.generateToken);
router.post('/tokens/validate', requireRole(['doctor', 'nurse', 'lab_technician', 'radiologist', 'pharmacist']), c.validateToken);
router.patch('/visits/:id/state', administration(), c.transitionVisitState);
router.get('/visits/:id/history', visitAccess(), c.getVisitStateHistory);
router.post('/care-team', administration(), assignedStaff, c.assignCareTeam);
router.delete('/care-team/:id', administration('careTeam'), c.removeCareTeam);
router.get('/visits/:id/care-team', visitAccess(), c.getVisitCareTeam);
router.post('/lab-orders', clinical('visit', 'write', ['doctor']), auditLog('create_lab_order', 'lab_order'), c.createLabOrder);
router.patch('/lab-orders/:id/status', clinical('labOrder', 'write', ['doctor', 'lab_technician']), c.updateLabOrderStatus);
router.get('/visits/:id/lab-orders', clinical(), c.getVisitLabOrders);
router.post('/imaging-orders', clinical('visit', 'write', ['doctor']), auditLog('create_imaging_order', 'imaging_order'), c.createImagingOrder);
router.patch('/imaging-orders/:id/status', clinical('imagingOrder', 'write', ['doctor', 'radiologist']), c.updateImagingOrderStatus);
router.get('/visits/:id/imaging-orders', clinical(), c.getVisitImagingOrders);
router.post('/medication-orders', clinical('visit', 'write', ['doctor']), auditLog('create_medication_order', 'medication_order'), c.createMedicationOrder);
router.patch('/medication-orders/:id/administer', clinical('medicationOrder', 'write', ['nurse']), c.administerMedication);
router.get('/visits/:id/medication-orders', clinical(), c.getVisitMedicationOrders);
router.post('/notifications', requireRole(['hospital_admin', 'doctor', 'nurse']), notificationTarget, c.sendNotification);
router.get('/notifications', c.getUserNotifications);
router.patch('/notifications/:id/read', c.markNotificationRead);
router.post('/bed-allocations', administration(), c.allocateBed);
router.patch('/bed-allocations/:id/release', administration('bed'), c.releaseBed);
router.get('/bed-allocations/available', requireRole(['hospital_admin', 'doctor', 'nurse', 'receptionist']), orgContext, c.getAvailableBeds);
router.get('/visits/:id/evaluate', administration(), c.evaluateVisit);
router.get('/logs', clinical('visit', 'read', ['doctor', 'nurse'], req => req.query.visitId), c.getWorkflowLogs);
module.exports = router;
