// Explicit maintenance command; production builds never contact Google Fonts.
// Re-run after adding icon names. Source and license metadata stay with the fonts.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const destination = path.join(root, 'src/assets/fonts');
const userAgent = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';
async function download(url) {
    const response = await fetch(url, { headers: { 'User-Agent': userAgent }, signal: AbortSignal.timeout(30000) });
    if (!response.ok) throw Error(`Font download failed: ${response.status} ${url}`);
    return Buffer.from(await response.arrayBuffer());
}
function sourceFiles(directory) {
    return fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
        const file = path.join(directory, entry.name);
        return entry.isDirectory() ? sourceFiles(file) : /\.(jsx?|css)$/.test(file) && !file.includes('.test.') ? [file] : [];
    });
}
const codepointsUrl = 'https://raw.githubusercontent.com/google/material-design-icons/master/variablefont/MaterialSymbolsOutlined%5BFILL%2CGRAD%2Copsz%2Cwght%5D.codepoints';
const codepoints = (await download(codepointsUrl)).toString();
const known = new Set(codepoints.split('\n').map(line => line.split(' ')[0]));
const source = sourceFiles(path.join(root, 'src')).map(file => fs.readFileSync(file, 'utf8')).join('\n');
const icons = [...new Set(source.match(/[a-z][a-z0-9_]+/g))].filter(name => known.has(name)).sort();
const textCssUrl = 'https://fonts.googleapis.com/css2?family=Plus+Jakarta+Sans:wght@300..700&display=swap';
const accentCssUrl = 'https://fonts.googleapis.com/css2?family=Courgette&text=care&display=swap';
const iconCssUrl = `https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:opsz,wght@24,400&icon_names=${icons.join(',')}&display=block`;
fs.mkdirSync(destination, { recursive: true });
const manifest = { codepointsUrl, icons, files: [] };
let textIndex = 0;
async function localFaces(cssUrl, prefix) {
    const css = (await download(cssUrl)).toString();
    const faces = [...css.matchAll(/@font-face\s*\{[^}]+\}/g)];
    if (!faces.length) throw Error('Font stylesheet contained no faces');
    const result = [];
    for (const [index, face] of faces.entries()) {
        const url = face[0].match(/url\((https:[^)]+)\)/)?.[1];
        if (!url || !/format\(['"]woff2['"]\)/.test(face[0])) throw Error('Expected WOFF2 font');
        const bytes = await download(url);
        if (bytes.toString('ascii', 0, 4) !== 'wOF2') throw Error('Invalid WOFF2 signature');
        const filename = `${prefix}-${index}.woff2`;
        fs.writeFileSync(path.join(destination, filename), bytes);
        manifest.files.push({ filename, source: url, stylesheet: cssUrl, bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') });
        if (prefix === 'plus-jakarta-sans' && /U\+0000-00FF/.test(face[0])) textIndex = index;
        // Icon ligatures need their ASCII names as well as glyph codepoints.
        const rule = prefix === 'material-symbols' ? face[0].replace(/\s*unicode-range:[^;]+;/g, '') : face[0];
        result.push(rule.replace(url, `../assets/fonts/${filename}`));
    }
    return result.join('\n');
}
const textFaces = await localFaces(textCssUrl, 'plus-jakarta-sans');
const accentFaces = await localFaces(accentCssUrl, 'courgette');
const iconFaces = await localFaces(iconCssUrl, 'material-symbols');
for (const [filename, url] of [
    ['PLUS-JAKARTA-SANS-OFL.txt', 'https://raw.githubusercontent.com/google/fonts/main/ofl/plusjakartasans/OFL.txt'],
    ['COURGETTE-OFL.txt', 'https://raw.githubusercontent.com/google/fonts/main/ofl/courgette/OFL.txt'],
    ['MATERIAL-SYMBOLS-LICENSE.txt', 'https://raw.githubusercontent.com/google/material-design-icons/master/LICENSE']
]) fs.writeFileSync(path.join(destination, filename), await download(url));
manifest.preload = `plus-jakarta-sans-${textIndex}.woff2`;
fs.writeFileSync(path.join(destination, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
fs.writeFileSync(path.join(destination, 'material-symbols.codepoints'), codepoints);
const block = `/* BEGIN SELF-HOSTED FONTS — generated by scripts/vendor-fonts.mjs */\n${textFaces}\n${accentFaces}\n${iconFaces}\n.material-symbols-outlined {\n    font-family: 'Material Symbols Outlined';\n    font-weight: 400;\n    font-style: normal;\n    font-size: 24px;\n    line-height: 1;\n    letter-spacing: normal;\n    text-transform: none;\n    display: inline-block;\n    white-space: nowrap;\n    word-wrap: normal;\n    direction: ltr;\n    -webkit-font-smoothing: antialiased;\n    font-feature-settings: 'liga';\n}\n/* END SELF-HOSTED FONTS */\n`;
const tokensFile = path.join(root, 'src/styles/tokens.css');
const tokens = fs.readFileSync(tokensFile, 'utf8').replace(/\/\* BEGIN SELF-HOSTED FONTS[\s\S]*?\/\* END SELF-HOSTED FONTS \*\/\r?\n/, '');
fs.writeFileSync(tokensFile, block + tokens);
const htmlFile = path.join(root, 'index.html');
fs.writeFileSync(htmlFile, fs.readFileSync(htmlFile, 'utf8').replace(/\/src\/assets\/fonts\/plus-jakarta-sans-\d+\.woff2/, `/src/assets/fonts/${manifest.preload}`));
process.stdout.write(`Vendored ${manifest.files.length} WOFF2 files (${manifest.files.reduce((sum,file)=>sum+file.bytes,0)} bytes), ${icons.length} icon names. Preload ${manifest.preload}.\n`);
